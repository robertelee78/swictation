function detectOrtLibrary() {
  log('cyan', '\n🔍 Detecting ONNX Runtime library path...');

  const isMacOS = process.platform === 'darwin';
  const ortFileName = isMacOS ? 'libonnxruntime.dylib' : 'libonnxruntime.so';

  // PRIORITY 1: Downloaded gpu-libs directory (ADR-035)
  // Same order generate-service.js uses to build LD_LIBRARY_PATH, so the model
  // verification below exercises the exact ONNX Runtime the service will load.
  try {
    const { getGpuLibsDir } = require('./src/paths');
    const gpuLibsOrtLib = path.join(getGpuLibsDir(), ortFileName);

    if (fs.existsSync(gpuLibsOrtLib)) {
      log('green', `✓ Found ONNX Runtime (downloaded gpu-libs): ${gpuLibsOrtLib}`);
      log('cyan', '  Using the same library the generated service loads');
      return gpuLibsOrtLib;
    }
  } catch (err) {
    // Paths module unavailable - continue to fallbacks
  }

  // PRIORITY 2: Check platform package library (new architecture)
  // Platform packages (@agidreams/linux-x64, @agidreams/darwin-arm64) include GPU-enabled ORT
  try {
    const { resolveBinaryPaths, isPlatformPackageInstalled } = require('./src/resolve-binary');
    if (isPlatformPackageInstalled()) {
      const binaryPaths = resolveBinaryPaths();
      const platformOrtLib = path.join(binaryPaths.libDir, ortFileName);

      if (fs.existsSync(platformOrtLib)) {
        log('green', `✓ Found ONNX Runtime (platform package): ${platformOrtLib}`);
        log('cyan', `  Using GPU-enabled library from ${binaryPaths.packageName}`);
        return platformOrtLib;
      }
    }
  } catch (err) {
    // Platform package not installed yet - continue to fallbacks
  }

  // PRIORITY 3: Check legacy bundled library path (deprecated, for backwards compatibility)
  const npmOrtLib = path.join(__dirname, 'lib', 'native', 'libonnxruntime.so');
  if (fs.existsSync(npmOrtLib)) {
    log('green', `✓ Found ONNX Runtime (bundled): ${npmOrtLib}`);
    log('cyan', '  Using bundled GPU-enabled library with CUDA provider support');
    return npmOrtLib;
  }

  // PRIORITY 4: Fall back to Python installation (usually CPU-only)
  log('yellow', '⚠️  Platform package ORT not found - checking Python fallback...');

  try {
    // Try to find ONNX Runtime through Python (fallback, usually CPU-only)
    const ortPath = execSync(
      'python3 -c "import onnxruntime; import os; print(os.path.join(os.path.dirname(onnxruntime.__file__), \'capi\'))"',
      { encoding: 'utf-8' }
    ).trim();

    if (!fs.existsSync(ortPath)) {
      log('yellow', '⚠️  Warning: ONNX Runtime capi directory not found at ' + ortPath);
      log('yellow', '   Daemon may not work correctly without onnxruntime-gpu');
      log('cyan', '   Install with: pip3 install onnxruntime-gpu');
      return null;
    }

    // Find the actual .so file
    const ortFiles = fs.readdirSync(ortPath).filter(f => f.startsWith('libonnxruntime.so'));

    if (ortFiles.length === 0) {
      log('yellow', '⚠️  Warning: Could not find libonnxruntime.so in ' + ortPath);
      log('yellow', '   Daemon may not work correctly');
      log('cyan', '   Install with: pip3 install onnxruntime-gpu');
      return null;
    }

    // Use the first (or only) .so file found
    const ortLibPath = path.join(ortPath, ortFiles[0]);
    log('yellow', `⚠️  Using Python ONNX Runtime: ${ortLibPath}`);
    log('yellow', '   Note: This may be CPU-only and lack CUDA support');

    // Store in a config file for systemd service generation
    const configDir = path.join(__dirname, 'config');
    const envFilePath = path.join(configDir, 'detected-environment.json');

    const envConfig = {
      ORT_DYLIB_PATH: ortLibPath,
      detected_at: new Date().toISOString(),
      onnxruntime_version: execSync('python3 -c "import onnxruntime; print(onnxruntime.__version__)"', { encoding: 'utf-8' }).trim(),
      warning: 'Using Python pip installation - may be CPU-only'
    };

    try {
      fs.writeFileSync(envFilePath, JSON.stringify(envConfig, null, 2));
      log('green', `✓ Saved environment config to ${envFilePath}`);
    } catch (err) {
      log('yellow', `Warning: Could not save environment config: ${err.message}`);
    }

    return ortLibPath;

  } catch (err) {
    const wrapped = new InstallError('SW-E010', 'Could not detect ONNX Runtime', {
      cause: err.message,
      fix: process.platform === 'darwin'
        ? 'ONNX Runtime should be provided by the platform package — try reinstalling: npm install -g swictation'
        : 'Install with: pip3 install onnxruntime-gpu\n         The daemon will not work correctly without this library',
      original: err,
    });
    console.log(wrapped.format());
    _installWarnings.push('ONNX Runtime not detected');
    return null;
  }
}

/**
 * @param {string} ortLibPath
 * @param {object} [facts] - resolved context facts (ADR-037 amendment 4).
 *   `binaryPaths` and `targetHome` come from the ONE context the install
 *   resolved: re-resolving here can pick a different platform package than
 *   the one just verified, and os.homedir() under sudo is not the home the
 *   check() that "verified" this unit reads from.
 */
function generateSystemdService(ortLibPath, facts = {}) {
  log('cyan', '\n⚙️  Generating systemd service files...');

  try {
    // Get platform package binary paths
    const { resolveBinaryPaths } = require('./src/resolve-binary');
    let binaryPaths;
    try {
      binaryPaths = facts.binaryPaths || resolveBinaryPaths();
      log('cyan', `  Using platform package: ${binaryPaths.packageName}`);
      log('cyan', `  Daemon binary: ${binaryPaths.daemon}`);
      log('cyan', `  Platform lib directory: ${binaryPaths.libDir}`);
    } catch (err) {
      log('red', `  ✗ Could not resolve platform package binaries: ${err.message}`);
      log('yellow', '  Service generation cannot proceed without platform package');
      return;
    }

    const homeDir = facts.targetHome || os.homedir();
    const systemdDir = path.join(homeDir, '.config', 'systemd', 'user');

    // Create systemd directory if it doesn't exist
    if (!fs.existsSync(systemdDir)) {
      fs.mkdirSync(systemdDir, { recursive: true });
      log('green', `✓ Created ${systemdDir}`);
    }

    // Detect display environment variables (used by both daemon and UI services)
    const runtimeDir = process.env.XDG_RUNTIME_DIR || `/run/user/${process.getuid()}`;
    let waylandDisplay = null;
    let xDisplay = process.env.DISPLAY || null;

    try {
      const sockets = fs.readdirSync(runtimeDir).filter(f => f.startsWith('wayland-'));
      if (sockets.length > 0) {
        // Use the first wayland socket (usually wayland-0 or wayland-1)
        waylandDisplay = sockets[0];
        log('cyan', `  Detected Wayland display: ${waylandDisplay}`);
      }
    } catch (err) {
      // Wayland socket not found, may be X11-only system
    }

    // 1. Generate daemon service from the shared template renderer (ADR-034:
    // single source of truth, shared with `swictation setup` in bin/swictation)
    try {
      const { buildDaemonServiceUnit } = require('./src/generate-service');
      const unit = buildDaemonServiceUnit(binaryPaths, log);
      const daemonServicePath = path.join(systemdDir, 'swictation-daemon.service');
      fs.writeFileSync(daemonServicePath, unit.content);
      log('green', `✓ Generated daemon service: ${daemonServicePath}`);
      if (!unit.ortFound) {
        log('yellow', '  ⚠️  ONNX Runtime not found - edit the service file to set ORT_DYLIB_PATH manually');
      }
    } catch (err) {
      log('red', `  ✗ Daemon service generation failed: ${err.message}`);
      log('yellow', '   Skipping daemon service generation');
    }

    // 2. Install UI service - detect environment and use appropriate UI
    // Sway/wlroots compositors: Use Python Qt tray (better Wayland support)
    // GNOME/KDE/X11: Use Tauri UI binary

    // CRITICAL: Environment variables may not be set during npm postinstall
    // So we use multiple detection methods that work regardless of environment:
    // 1. Check running compositor processes (most reliable)
    // 2. Check for compositor sockets
    // 3. Fall back to environment variables if available

    let isSway = false;
    let isHyprland = false;
    let isRiver = false;
    let detectedCompositor = 'unknown';

    // Method 1: Check running processes (works even without env vars)
    try {
      const pgrepSway = execSync('pgrep -x sway 2>/dev/null || true', { encoding: 'utf8' }).trim();
      if (pgrepSway) {
        isSway = true;
        detectedCompositor = 'sway';
      }
    } catch (e) { /* ignore */ }

    try {
      const pgrepHyprland = execSync('pgrep -x Hyprland 2>/dev/null || true', { encoding: 'utf8' }).trim();
      if (pgrepHyprland) {
        isHyprland = true;
        detectedCompositor = 'hyprland';
      }
    } catch (e) { /* ignore */ }

    try {
      const pgrepRiver = execSync('pgrep -x river 2>/dev/null || true', { encoding: 'utf8' }).trim();
      if (pgrepRiver) {
        isRiver = true;
        detectedCompositor = 'river';
      }
    } catch (e) { /* ignore */ }

    // Method 2: Check for sway IPC socket
    const uid = process.getuid();
    const swaySocketDir = `/run/user/${uid}`;
    try {
      if (fs.existsSync(swaySocketDir)) {
        const files = fs.readdirSync(swaySocketDir);
        if (files.some(f => f.startsWith('sway-ipc'))) {
          isSway = true;
          detectedCompositor = 'sway';
        }
      }
    } catch (e) { /* ignore */ }

    // Method 3: Check Hyprland socket directory
    try {
      const hyprDir = path.join(swaySocketDir, 'hypr');
      if (fs.existsSync(hyprDir)) {
        isHyprland = true;
        detectedCompositor = 'hyprland';
      }
    } catch (e) { /* ignore */ }

    // Method 4: Environment variables (fallback, may not be available)
    if (!isSway && !isHyprland && !isRiver) {
      isSway = !!process.env.SWAYSOCK || process.env.XDG_CURRENT_DESKTOP?.toLowerCase().includes('sway');
      isHyprland = process.env.XDG_CURRENT_DESKTOP?.toLowerCase().includes('hyprland') || !!process.env.HYPRLAND_INSTANCE_SIGNATURE;
      isRiver = process.env.XDG_CURRENT_DESKTOP?.toLowerCase().includes('river');

      if (isSway) detectedCompositor = 'sway';
      else if (isHyprland) detectedCompositor = 'hyprland';
      else if (isRiver) detectedCompositor = 'river';
    }

    const isWlroots = isSway || isHyprland || isRiver;
    const isWayland = !!process.env.WAYLAND_DISPLAY || process.env.XDG_SESSION_TYPE === 'wayland';

    log('cyan', `  Compositor detection: ${detectedCompositor} (wlroots: ${isWlroots})`);

    let uiServiceContent;
    const uiServiceDest = path.join(systemdDir, 'swictation-ui.service');

    if (isWlroots) {
      // Use Python Qt tray for wlroots-based compositors (Sway, Hyprland, River)
      // These compositors have better Qt/PySide6 tray support than Tauri/libappindicator
      const pythonTrayPath = path.join(__dirname, 'src', 'ui', 'swictation_tray.py');
      log('cyan', `  Detected wlroots compositor: ${detectedCompositor} - using Python Qt tray`);

      uiServiceContent = `[Unit]
Description=Swictation System Tray (Python/Qt)
After=swictation-daemon.service
Requires=swictation-daemon.service
BindsTo=swictation-daemon.service
PartOf=swictation-daemon.service

[Service]
Type=simple
ExecStart=/usr/bin/python3 ${pythonTrayPath}
Restart=on-failure
RestartSec=5

Environment="DISPLAY=${xDisplay || ':0'}"
Environment="WAYLAND_DISPLAY=${waylandDisplay || 'wayland-1'}"
Environment="QT_QPA_PLATFORM=wayland"
Environment="XDG_RUNTIME_DIR=/run/user/${process.getuid()}"

MemoryMax=100M
CPUQuota=10%

[Install]
WantedBy=default.target
`;
      fs.writeFileSync(uiServiceDest, uiServiceContent);
      log('green', `✓ Installed Python Qt tray service: ${uiServiceDest}`);
    } else {
      // Use Tauri UI for GNOME, KDE, or X11 environments
      const uiServiceTemplate = path.join(__dirname, 'templates', 'swictation-ui.service.template');
      if (fs.existsSync(uiServiceTemplate)) {
        let uiTemplate = fs.readFileSync(uiServiceTemplate, 'utf8');

        // Replace placeholders with platform package UI binary path
        uiTemplate = uiTemplate.replace(/__INSTALL_DIR__/g, binaryPaths.binDir);
        uiTemplate = uiTemplate.replace(/__DISPLAY__/g, xDisplay || ':0');
        uiTemplate = uiTemplate.replace(/__WAYLAND_DISPLAY__/g, waylandDisplay || 'wayland-0');

        fs.writeFileSync(uiServiceDest, uiTemplate);
        log('green', `✓ Installed Tauri UI service: ${uiServiceDest}`);
      } else {
        log('yellow', `⚠️  Warning: UI service template not found at ${uiServiceTemplate}`);
        log('yellow', '   You can manually create it later');
      }
    }

    // CRITICAL: Reload systemd to pick up service file changes
    // Without this, systemd uses cached versions and services fail to start with old paths
    log('cyan', '\n🔄 Reloading systemd daemon...');
    try {
      execSync('systemctl --user daemon-reload', { stdio: 'ignore' });
      log('green', '✓ Systemd daemon reloaded - service files updated');
    } catch (err) {
      log('yellow', `⚠️  Could not reload systemd: ${err.message}`);
      log('yellow', '   You may need to run manually: systemctl --user daemon-reload');
    }

  } catch (err) {
    const wrapped = InstallError.fromSystemError(err, 'SW-E006', 'Failed to generate systemd services', { path: path.join(facts.targetHome || os.homedir(), '.config', 'systemd', 'user') });
    console.log(wrapped.format());
    log('cyan', '  You can manually create them later using: swictation setup');
    _installWarnings.push('Systemd service generation failed');
  }
}

const LAUNCHD_LABELS = { daemon: 'com.swictation.daemon', ui: 'com.swictation.ui' };

/**
 * LOADED and RUNNING, from one `launchctl print` block.
 *
 * `launchctl print` exiting 0 means the job is BOOTSTRAPPED — it exists in the
 * domain. It says nothing about whether it has a process. A job that is loaded
 * and stopped prints `state = not running` and carries no top-level `pid`, and
 * conflating that with "running" is what made restore-after-decline start a
 * service the user had deliberately stopped.
 *
 * Only TOP-LEVEL keys count (one tab of indentation): the block nests
 * `endpoints` and `spawn statistics` sub-dictionaries that carry their own
 * `state = active` lines, and a looser match reads an endpoint's liveness as
 * the job's.
 *
 * @param {string} output
 * @returns {{loaded: boolean, running: boolean}}
 */
function parseLaunchctlPrint(output) {
  const pid = /^\tpid = (\d+)$/m.exec(output);
  const state = /^\tstate = (.+)$/m.exec(output);
  return {
    loaded: true,
    running: !!pid || (!!state && state[1].trim() === 'running'),
  };
}

/**
 * What each LaunchAgent is doing in this user's GUI domain, right now.
 *
 * Read-only, and the only honest way to answer "was this running before I
 * touched it": regenerating plists boots the agents out, so a caller that
 * wants to leave the machine as it found it has to ask BEFORE that happens.
 * A user who declines auto-start expects their already-running daemon to keep
 * running, not to be silently stopped by a setup they ran for another reason.
 *
 * @returns {{daemon: {loaded: boolean, running: boolean}, ui: {loaded: boolean, running: boolean}}}
 */
function launchdServiceState() {
  const absent = () => ({ loaded: false, running: false });
  const state = { daemon: absent(), ui: absent() };
  if (process.platform !== 'darwin') return state;
  let uid;
  try {
    uid = execFileSync('id', ['-u'], { encoding: 'utf8' }).trim();
  } catch {
    return state;
  }
  for (const [key, label] of Object.entries(LAUNCHD_LABELS)) {
    try {
      const out = execFileSync('launchctl', ['print', `gui/${uid}/${label}`], {
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      });
      state[key] = parseLaunchctlPrint(out);
    } catch {
      state[key] = absent();
    }
  }
  return state;
}

/**
 * Bootstrap the LaunchAgents that were RUNNING before this install touched
 * them. Used to undo the bootout that plist regeneration performs when the
 * caller is NOT going to load them itself.
 *
 * Running, not merely loaded, and the distinction decides behaviour: the
 * generated plists carry RunAtLoad, so bootstrapping a job that was loaded and
 * STOPPED would start it — turning "put the machine back as I found it" into
 * "start a service the user had stopped". Those jobs are left alone.
 *
 * @param {{daemon: {running: boolean}, ui: {running: boolean}}} wasRunning
 * @param {string} [homeDir]
 * @returns {string[]} labels that were restored
 */
function restoreLaunchdServices(wasRunning = {}, homeDir = os.homedir()) {
  if (process.platform !== 'darwin') return [];
  const restored = [];
  let uid;
  try {
    uid = execFileSync('id', ['-u'], { encoding: 'utf8' }).trim();
  } catch {
    return restored;
  }
  for (const [key, label] of Object.entries(LAUNCHD_LABELS)) {
    const previous = wasRunning[key];
    if (!previous || previous.running !== true) continue;
    const plist = path.join(homeDir, 'Library', 'LaunchAgents', `${label}.plist`);
    if (!fs.existsSync(plist)) continue;
    try {
      execFileSync('launchctl', ['bootstrap', `gui/${uid}`, plist], {
        stdio: ['ignore', 'ignore', 'ignore'],
      });
      restored.push(label);
    } catch {
      // Already bootstrapped, or launchd refused: either way the caller's
      // report below is what the user sees, and a failure here is not worth
      // failing a setup over.
    }
  }
  return restored;
}

/**
 * Generate LaunchAgent plist files for macOS
 * LaunchAgents are macOS equivalent of systemd user services
 *
 * @param {string} ortLibPath
 * @param {object} [options]
 * @param {boolean} [options.load=true] - bootstrap and start the agents once
 *   written. `swictation setup` passes false: it asks the user about
 *   auto-start AFTER generating, and loading here would make answering "No"
 *   meaningless (ADR-037 amendment, P1).
 * @param {object} [options.binaryPaths] - resolved context fact; re-resolving
 *   here can pick a different platform package than the install just verified.
 * @param {string} [options.targetHome] - resolved context fact; os.homedir()
 *   under sudo is not the home whose plist the check() reads.
 * @returns {{wasRunning: {daemon: boolean, ui: boolean}, loaded: boolean}}
 *   `wasRunning` is the state observed BEFORE the bootout, so a caller that
 *   passed `load:false` can put the machine back the way it found it.
 */
function generateLaunchdServices(ortLibPath, options = {}) {
  const { load = true } = options;
  log('cyan', '\n⚙️  Generating launchd service files...');

  // Sampled before anything is booted out — afterwards the answer is always
  // "not running" and the information is gone for good.
  const wasRunning = launchdServiceState();
  const result = { wasRunning, loaded: load };

  try {
    // Get platform package binary paths
    const { resolveBinaryPaths } = require('./src/resolve-binary');
    let binaryPaths;
    try {
      binaryPaths = options.binaryPaths || resolveBinaryPaths();
      log('cyan', `  Using platform package: ${binaryPaths.packageName}`);
      log('cyan', `  Daemon binary: ${binaryPaths.daemon}`);
      log('cyan', `  UI binary: ${binaryPaths.ui}`);
      log('cyan', `  Platform lib directory: ${binaryPaths.libDir}`);
    } catch (err) {
      log('red', `  ✗ Could not resolve platform package binaries: ${err.message}`);
      log('yellow', '  Service generation cannot proceed without platform package');
      return result;
    }

    const targetHome = options.targetHome || os.homedir();
    const launchAgentsDir = path.join(targetHome, 'Library', 'LaunchAgents');
    const logDir = path.join(targetHome, 'Library', 'Logs', 'swictation');
    const daemonPlistPath = path.join(launchAgentsDir, 'com.swictation.daemon.plist');
    const uiPlistPath = path.join(launchAgentsDir, 'com.swictation.ui.plist');

    // Step 1: Stop and unload any existing services FIRST
    // This ensures we can safely update the plist files
    log('cyan', '  Stopping any existing services...');

    // Unload daemon service (ignore errors if not loaded)
    try {
      execSync('launchctl bootout gui/$(id -u) com.swictation.daemon 2>/dev/null || true', { shell: '/bin/bash' });
    } catch (e) { /* ignore */ }
    try {
      execSync(`launchctl unload "${daemonPlistPath}" 2>/dev/null || true`, { shell: '/bin/bash' });
    } catch (e) { /* ignore */ }

    // Unload UI service (ignore errors if not loaded)
    try {
      execSync('launchctl bootout gui/$(id -u) com.swictation.ui 2>/dev/null || true', { shell: '/bin/bash' });
    } catch (e) { /* ignore */ }
    try {
      execSync(`launchctl unload "${uiPlistPath}" 2>/dev/null || true`, { shell: '/bin/bash' });
    } catch (e) { /* ignore */ }

    log('green', '  ✓ Existing services stopped');

    // Rotate log files from previous run to prevent diagnostic confusion
    const logFiles = ['daemon.log', 'daemon-error.log', 'ui.log', 'ui-error.log', 'launcher.log'];
    for (const logFile of logFiles) {
        const logPath = path.join(logDir, logFile);
        const prevPath = path.join(logDir, logFile + '.prev');
        try {
            if (fs.existsSync(logPath)) {
                if (fs.existsSync(prevPath)) {
                    fs.unlinkSync(prevPath);
                }
                fs.renameSync(logPath, prevPath);
            }
        } catch (rotateErr) {
            // Non-fatal: log rotation failure should not block upgrade
        }
    }
    log('green', '  ✓ Previous log files rotated');

    // Create directories
    if (!fs.existsSync(launchAgentsDir)) {
      fs.mkdirSync(launchAgentsDir, { recursive: true });
      log('green', `✓ Created ${launchAgentsDir}`);
    }
    if (!fs.existsSync(logDir)) {
      fs.mkdirSync(logDir, { recursive: true });
      log('green', `✓ Created ${logDir}`);
    }

    // Step 2: Generate daemon plist from template
    const daemonTemplatePath = path.join(__dirname, 'templates', 'macos', 'com.swictation.daemon.plist');
    if (!fs.existsSync(daemonTemplatePath)) {
      log('yellow', `⚠️  Warning: Template not found at ${daemonTemplatePath}`);
      log('yellow', '   Skipping daemon service generation');
    } else {
      let daemonTemplate = fs.readFileSync(daemonTemplatePath, 'utf8');

      // Replace template variables
      // Use platform package binary paths instead of __dirname
      const daemonBinaryPath = binaryPaths.daemon;
      const homeDir = targetHome;

      // DYLD_LIBRARY_PATH: CoreML runtime + ONNX Runtime providers
      // ORT_DYLIB_PATH: Points to CoreML-enabled ONNX Runtime
      // The CoreML dylib is downloaded to the main package's lib/native directory
      // by downloadONNXRuntimeCoreML(), NOT the platform package's lib directory.
      // We need to check where it actually exists and use that path.
      const mainPackageNativeDir = path.join(__dirname, 'lib', 'native');
      const mainPackageOrtPath = path.join(mainPackageNativeDir, 'libonnxruntime.dylib');
      const platformOrtPath = path.join(binaryPaths.libDir, 'libonnxruntime.dylib');

      let dylibPath;
      let ortDylibPath;

      if (fs.existsSync(mainPackageOrtPath)) {
        // CoreML dylib was downloaded to main package native dir (expected case)
        dylibPath = mainPackageNativeDir;
        ortDylibPath = mainPackageOrtPath;
        log('cyan', `  Found CoreML dylib in main package: ${mainPackageOrtPath}`);
      } else if (fs.existsSync(platformOrtPath)) {
        // Fallback: check platform package lib dir
        dylibPath = binaryPaths.libDir;
        ortDylibPath = platformOrtPath;
        log('cyan', `  Found CoreML dylib in platform package: ${platformOrtPath}`);
      } else {
        // Neither exists - use main package path and warn
        dylibPath = mainPackageNativeDir;
        ortDylibPath = mainPackageOrtPath;
        log('yellow', `  ⚠️  CoreML dylib not found at expected locations`);
        log('yellow', `     Expected: ${mainPackageOrtPath}`);
        log('yellow', `     Fallback: ${platformOrtPath}`);
      }

      // CRITICAL: macOS SIP (System Integrity Protection) strips DYLD_* environment
      // variables from launchd processes. We MUST use a wrapper script that sets
      // the environment variables before executing the daemon binary.
      // Wrapper script goes in main package bin/ directory, executes daemon from platform package
      const mainPackageDir = __dirname; // Main swictation package directory
      const wrapperScriptPath = path.join(mainPackageDir, 'bin', 'swictation-daemon-launcher');
      // CRITICAL: Use string concatenation to avoid JavaScript template literal
      // interpolation of shell variables. Shell variables like ${VAR} must be
      // preserved in the output, not replaced with JavaScript values at write time.
      const wrapperScript = '#!/bin/bash\n' +
'# Wrapper script for swictation-daemon on macOS\n' +
'# Required because SIP strips DYLD_* env vars from launchd processes\n' +
'#\n' +
'# This script sets the necessary environment variables for ONNX Runtime\n' +
'# CoreML acceleration before launching the daemon binary.\n' +
'#\n' +
'# IMPORTANT: Paths are resolved at runtime using SCRIPT_DIR to handle\n' +
'# npm reinstalls and path changes gracefully.\n' +
'\n' +
'# Resolve the directory where this script is located\n' +
'SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"\n' +
'PACKAGE_DIR="$(dirname "$SCRIPT_DIR")"\n' +
'\n' +
'# Platform package lib directory (for ONNX Runtime dylib)\n' +
'# Try multiple locations in priority order:\n' +
'# 1. Sibling: platform package hoisted by npm (global installs)\n' +
'# 2. Nested: platform package as nested dep (local installs, npm 7+)\n' +
'# 3. Main package lib/native directory\n' +
'# 4. Hardcoded install-time fallback\n' +
'find_onnx_lib() {\n' +
'    # Check sibling platform package first (preferred - has signed dylib)\n' +
'    local sibling_lib="$PACKAGE_DIR/../@agidreams/darwin-arm64/lib"\n' +
'    if [ -f "$sibling_lib/libonnxruntime.dylib" ]; then\n' +
'        echo "$sibling_lib"\n' +
'        return\n' +
'    fi\n' +
'    \n' +
'    # Check nested platform package (npm 7+ nesting or local installs)\n' +
'    local nested_lib="$PACKAGE_DIR/node_modules/@agidreams/darwin-arm64/lib"\n' +
'    if [ -f "$nested_lib/libonnxruntime.dylib" ]; then\n' +
'        echo "$nested_lib"\n' +
'        return\n' +
'    fi\n' +
'    \n' +
'    # Check main package lib/native directory\n' +
'    local main_lib="$PACKAGE_DIR/lib/native"\n' +
'    if [ -f "$main_lib/libonnxruntime.dylib" ]; then\n' +
'        echo "$main_lib"\n' +
'        return\n' +
'    fi\n' +
'    \n' +
'    # Fallback to explicit path from install time (may be stale)\n' +
'    echo "' + dylibPath + '"\n' +
'}\n' +
'\n' +
'# Resolve library path at runtime\n' +
'LIB_DIR="$(find_onnx_lib)"\n' +
'\n' +
'# Set library path for ONNX Runtime dylib (required for CoreML GPU acceleration)\n' +
'export DYLD_LIBRARY_PATH="$LIB_DIR:${DYLD_LIBRARY_PATH:-}"\n' +
'\n' +
'# Set explicit ONNX Runtime dylib path (critical for model loading)\n' +
'export ORT_DYLIB_PATH="$LIB_DIR/libonnxruntime.dylib"\n' +
'\n' +
'# Find the daemon binary (prefer platform package)\n' +
'DAEMON_BIN="$PACKAGE_DIR/../@agidreams/darwin-arm64/bin/swictation-daemon"\n' +
'if [ ! -x "$DAEMON_BIN" ]; then\n' +
'    # Check nested platform package (npm 7+ nesting or local installs)\n' +
'    DAEMON_BIN="$PACKAGE_DIR/node_modules/@agidreams/darwin-arm64/bin/swictation-daemon"\n' +
'fi\n' +
'if [ ! -x "$DAEMON_BIN" ]; then\n' +
'    # Fallback to explicit path from install time\n' +
'    DAEMON_BIN="' + daemonBinaryPath + '"\n' +
'fi\n' +
'\n' +
'# Diagnostic trace for debugging path resolution\n' +
'LOG_DIR="$HOME/Library/Logs/swictation"\n' +
'mkdir -p "$LOG_DIR" 2>/dev/null\n' +
'echo "$(date \'+%Y-%m-%d %H:%M:%S\') ORT_DYLIB_PATH=$ORT_DYLIB_PATH DAEMON_BIN=$DAEMON_BIN LIB_DIR=$LIB_DIR" >> "$LOG_DIR/launcher.log"\n' +
'\n' +
'# Execute the actual daemon binary\n' +
'exec "$DAEMON_BIN" "$@"\n';

      // Write the wrapper script
      fs.writeFileSync(wrapperScriptPath, wrapperScript);
      fs.chmodSync(wrapperScriptPath, 0o755); // rwxr-xr-x (executable)
      log('green', `  ✓ Generated daemon launcher wrapper: ${wrapperScriptPath}`);

      // Point plist to wrapper script instead of binary directly
      daemonTemplate = daemonTemplate.replace(/\{\{DAEMON_PATH\}\}/g, wrapperScriptPath);
      daemonTemplate = daemonTemplate.replace(/\{\{LOG_DIR\}\}/g, logDir);
      daemonTemplate = daemonTemplate.replace(/\{\{HOME\}\}/g, homeDir);
      daemonTemplate = daemonTemplate.replace(/\{\{ORT_DYLIB_PATH\}\}/g, ortDylibPath);

      log('cyan', `  Daemon binary: ${daemonBinaryPath}`);
      log('cyan', `  Launcher wrapper: ${wrapperScriptPath}`);
      log('cyan', `  ORT_DYLIB_PATH: ${ortDylibPath}`);

      // Write daemon plist (uses outer daemonPlistPath declared at function scope)
      fs.writeFileSync(daemonPlistPath, daemonTemplate);
      fs.chmodSync(daemonPlistPath, 0o644); // rw-r--r--
      log('green', `✓ Generated daemon plist: ${daemonPlistPath}`);

      // Validate plist (optional, requires plutil)
      try {
        execSync(`plutil -lint "${daemonPlistPath}"`, { stdio: 'ignore' });
        log('green', `  ✓ Daemon plist validated successfully`);
      } catch (err) {
        log('yellow', `  ⚠️  Could not validate plist (plutil not available)`);
      }
    }

    // 2. Generate UI plist from template (if UI binary exists)
    // UI binary comes from platform package
    const uiPath = binaryPaths.ui;
    if (fs.existsSync(uiPath)) {
      const uiTemplatePath = path.join(__dirname, 'templates', 'macos', 'com.swictation.ui.plist');
      if (!fs.existsSync(uiTemplatePath)) {
        log('yellow', `⚠️  Warning: UI template not found at ${uiTemplatePath}`);
      } else {
        let uiTemplate = fs.readFileSync(uiTemplatePath, 'utf8');

        // Replace template variables
        const homeDir = targetHome;
        uiTemplate = uiTemplate.replace(/\{\{UI_PATH\}\}/g, uiPath);
        uiTemplate = uiTemplate.replace(/\{\{LOG_DIR\}\}/g, logDir);
        uiTemplate = uiTemplate.replace(/\{\{HOME\}\}/g, homeDir);

        log('cyan', `  UI binary: ${uiPath}`);

        // Write UI plist (uses outer uiPlistPath declared at function scope)
        fs.writeFileSync(uiPlistPath, uiTemplate);
        fs.chmodSync(uiPlistPath, 0o644); // rw-r--r--
        log('green', `✓ Generated UI plist: ${uiPlistPath}`);

        // Validate plist
        try {
          execSync(`plutil -lint "${uiPlistPath}"`, { stdio: 'ignore' });
          log('green', `  ✓ UI plist validated successfully`);
        } catch (err) {
          log('yellow', `  ⚠️  Could not validate plist (plutil not available)`);
        }
      }
    } else {
      log('cyan', `  ℹ UI binary not found - skipping UI service`);
    }

    // Step 3: Auto-load and start services
    if (!load) {
      log('cyan', '\n  Plists written; not loading them here.');
      log('cyan', '  (auto-start is a separate, explicit choice)');
      // Regenerating the plists booted these out. Whoever passed load:false
      // owns the decision to bring them back — `wasRunning` is how they know
      // which ones to restore, and it is the only record left.
      const stopped = Object.entries(wasRunning)
        .filter(([, previous]) => previous && previous.running)
        .map(([key]) => key);
      if (stopped.length > 0) {
        log('cyan', `  (${stopped.join(' and ')} was running and is now stopped)`);
      }
      return result;
    }
    log('cyan', '\n  Loading services with launchd...');

    // Load daemon service (enables auto-start on login)
    if (fs.existsSync(daemonPlistPath)) {
      try {
        // Bootstrap is the modern way to load services
        execSync(`launchctl bootstrap gui/$(id -u) "${daemonPlistPath}" 2>/dev/null || launchctl load "${daemonPlistPath}"`, { shell: '/bin/bash' });
        log('green', '  ✓ Daemon service loaded');

        // Start the daemon
        try {
          execSync('launchctl start com.swictation.daemon 2>/dev/null || true', { shell: '/bin/bash' });
          log('green', '  ✓ Daemon service started');
        } catch (startErr) {
          log('yellow', `  ⚠️  Daemon start deferred (will start on next login)`);
        }
      } catch (loadErr) {
        log('yellow', `  ⚠️  Could not auto-load daemon: ${loadErr.message}`);
        log('cyan', '  To load manually: launchctl load ~/Library/LaunchAgents/com.swictation.daemon.plist');
      }
    }

    // Load UI service
    const uiPlistFinal = path.join(launchAgentsDir, 'com.swictation.ui.plist');
    if (fs.existsSync(uiPlistFinal)) {
      try {
        execSync(`launchctl bootstrap gui/$(id -u) "${uiPlistFinal}" 2>/dev/null || launchctl load "${uiPlistFinal}"`, { shell: '/bin/bash' });
        log('green', '  ✓ UI service loaded');

        // Start the UI
        try {
          execSync('launchctl start com.swictation.ui 2>/dev/null || true', { shell: '/bin/bash' });
          log('green', '  ✓ UI service started');
        } catch (startErr) {
          log('yellow', `  ⚠️  UI start deferred (will start on next login)`);
        }
      } catch (loadErr) {
        log('yellow', `  ⚠️  Could not auto-load UI: ${loadErr.message}`);
        log('cyan', '  To load manually: launchctl load ~/Library/LaunchAgents/com.swictation.ui.plist');
      }
    }

    log('green', '\n✅ LaunchAgent services configured and started');
    log('cyan', '\nServices will auto-start on login. Use these commands to manage:');
    log('cyan', '  swictation status    - Check service status');
    log('cyan', '  swictation start     - Start services');
    log('cyan', '  swictation stop      - Stop services');

    return result;
  } catch (err) {
    const wrapped = InstallError.fromSystemError(err, 'SW-E006', 'Failed to generate launchd services', { path: path.join(options.targetHome || os.homedir(), 'Library', 'LaunchAgents') });
    console.log(wrapped.format());
    log('cyan', '  You can manually create them later using: swictation setup');
    _installWarnings.push('LaunchAgent service generation failed');
    return result;
  }
}

/**
 * Phase 3: Detect GPU VRAM for intelligent model selection
 * Prevents loading models that are too large for available VRAM
 */
function detectGPUVRAM() {
  log('cyan', '\n🎮 Detecting GPU capabilities...');

  const gpuInfo = {
    hasGPU: false,
    gpuName: null,
    vramMB: 0,
    vramGB: 0,
    cudaVersion: null,
    driverVersion: null,
    recommendedModel: null
  };

  if (!detectNvidiaGPU()) {
    log('cyan', '  No NVIDIA GPU detected - CPU mode will be used');
    // cpu-only is a real recommendation (VAD + 0.6b on CPU), not an absence
    // of one — a null here made cpu-only Linux installs fail before ever
    // downloading a model (ADR-037 adjudication P0).
    gpuInfo.recommendedModel = 'cpu-only';
    return gpuInfo;
  }

  gpuInfo.hasGPU = true;

  try {
    // Get comprehensive GPU information
    const gpuData = execSync(
      'nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader,nounits',
      { encoding: 'utf8' }
    ).trim();

    const [name, vramMB, driver] = gpuData.split(',').map(s => s.trim());

    gpuInfo.gpuName = name;
    gpuInfo.vramMB = parseInt(vramMB);
    gpuInfo.vramGB = Math.floor(gpuInfo.vramMB / 1024);
    gpuInfo.driverVersion = driver;

    // Try to get CUDA version
    try {
      const cudaVersion = execSync('nvidia-smi | grep "CUDA Version" | awk \'{print $9}\'', { encoding: 'utf8' }).trim();
      if (cudaVersion) {
        gpuInfo.cudaVersion = cudaVersion;
      }
    } catch {
      // CUDA version detection optional
    }

    log('green', `✓ GPU Detected: ${gpuInfo.gpuName}`);
    log('cyan', `  VRAM: ${gpuInfo.vramGB}GB (${gpuInfo.vramMB}MB)`);
    log('cyan', `  Driver: ${gpuInfo.driverVersion}`);
    if (gpuInfo.cudaVersion) {
      log('cyan', `  CUDA: ${gpuInfo.cudaVersion}`);
    }

    // Intelligent model recommendation based on VRAM
    // Based on empirical data from real-world testing:
    // 0.6B model: ~3.5GB VRAM (fits in 4GB with headroom) - VERIFIED ON RTX A1000
    // 1.1B model: ~6GB VRAM (needs at least 6GB for safety)
    if (gpuInfo.vramMB >= 6000) {
      // 6GB+ VRAM: Can safely run 1.1B model
      gpuInfo.recommendedModel = '1.1b-gpu';
      log('green', `  ✓ Sufficient VRAM for 1.1B model (best quality)`);
    } else if (gpuInfo.vramMB >= 3500) {
      // 3.5-6GB VRAM: Run 0.6B model (proven safe on 4GB)
      // This includes exactly 4GB GPUs like RTX A1000
      gpuInfo.recommendedModel = '0.6b-gpu';
      if (gpuInfo.vramMB >= 4000) {
        log('green', `  ✓ VRAM sufficient for 0.6B GPU model`);
      } else {
        log('yellow', `  ⚠️  Limited VRAM - Recommending 0.6B model`);
      }
      log('cyan', `     (1.1B model requires ~6GB VRAM)`);
    } else {
      // <3.5GB VRAM: Too little for GPU acceleration
      gpuInfo.recommendedModel = 'cpu-only';
      log('yellow', `  ⚠️  Insufficient VRAM for GPU models`);
      log('cyan', `     GPU models require minimum 3.5GB VRAM`);
      log('cyan', `     Falling back to CPU-only mode`);
    }

    // Save GPU info for later use by daemon
    const configDir = getConfigDir();
    const gpuInfoPath = path.join(configDir, 'gpu-info.json');

    try {
      fs.writeFileSync(gpuInfoPath, JSON.stringify(gpuInfo, null, 2));
      log('green', `  ✓ Saved GPU info to ${gpuInfoPath}`);
    } catch (err) {
      log('yellow', `  ⚠️  Could not save GPU info: ${err.message}`);
    }

  } catch (err) {
    log('yellow', `⚠️  Error detecting GPU details: ${err.message}`);
    log('cyan', '   GPU detected but could not read specifications');
  }

  return gpuInfo;
}

/**
 * Detect unified memory on macOS (Apple Silicon)
 * macOS uses unified memory architecture - no separate VRAM
 * We apply 65/35 split: 65% for system, 35% for GPU
 */
function detectUnifiedMemoryMacOS() {
  log('cyan', '\n🍎 Detecting macOS unified memory...');

  const gpuInfo = {
    hasGPU: true, // Apple Silicon always has GPU (Metal)
    gpuName: 'Apple Silicon GPU',
    totalMemoryMB: 0,
    totalMemoryGB: 0,
    gpuMemoryMB: 0,
    gpuMemoryGB: 0,
    vramMB: 0,
    vramGB: 0,
    metalVersion: null,
    driverVersion: null,
    recommendedModel: null
  };

  try {
    // Get total system memory in bytes
    const totalMemBytes = os.totalmem();
    gpuInfo.totalMemoryMB = Math.round(totalMemBytes / (1024 * 1024));
    gpuInfo.totalMemoryGB = Math.round(gpuInfo.totalMemoryMB / 1024);

    // Hard gate: macOS requires 16GB+ unified memory
    if (gpuInfo.totalMemoryMB < 14500) {
      log('red', `\n✖ Swictation on macOS requires 16GB+ unified memory.`);
      log('red', `  Detected: ${gpuInfo.totalMemoryGB}GB total system RAM.`);
      log('red', `  The CoreML speech models need at least 16GB to run reliably.`);
      process.exit(1);
    }

    // Apply 65/35 split (matches gpu.rs implementation)
    gpuInfo.gpuMemoryMB = Math.round(gpuInfo.totalMemoryMB * 0.35);
    gpuInfo.gpuMemoryGB = Math.round(gpuInfo.gpuMemoryMB / 1024);
    gpuInfo.vramMB = gpuInfo.gpuMemoryMB;
    gpuInfo.vramGB = gpuInfo.gpuMemoryGB;

    // Detect GPU model name
    try {
      const gpuName = execSync('system_profiler SPDisplaysDataType | grep "Chipset Model" | head -1 | cut -d: -f2',
        { encoding: 'utf8' }).trim();
      if (gpuName) {
        gpuInfo.gpuName = gpuName;
      }
    } catch (err) {
      // GPU name detection optional
    }

    // Detect Metal version
    try {
      const metalVersion = execSync('system_profiler SPDisplaysDataType | grep "Metal Support" | head -1 | cut -d: -f2',
        { encoding: 'utf8' }).trim();
      if (metalVersion) {
        gpuInfo.metalVersion = metalVersion;
        gpuInfo.driverVersion = 'Metal ' + metalVersion.trim();
      }
    } catch (err) {
      // Metal version detection optional
    }

    log('green', `✓ GPU: ${gpuInfo.gpuName}`);
    log('cyan', `  Total Memory: ${gpuInfo.totalMemoryGB}GB (${gpuInfo.totalMemoryMB}MB)`);
    log('cyan', `  GPU Share (35%): ${gpuInfo.gpuMemoryGB}GB (${gpuInfo.gpuMemoryMB}MB)`);
    if (gpuInfo.metalVersion) {
      log('cyan', `  Metal: ${gpuInfo.metalVersion}`);
    }

    // macOS Apple Silicon: Always use native CoreML 1.1B model
    // All supported Macs (M1-M5) have sufficient unified memory for the 1.9GB model.
    // Native CoreML provides full ANE (Apple Neural Engine) acceleration.
    gpuInfo.recommendedModel = '1.1b-coreml';
    log('green', `  ✓ Apple Silicon detected — using native CoreML 1.1B model`);
    log('cyan', `     Full ANE acceleration via coreml-native`);

    // Save GPU info for later use by daemon
    const configDir = getConfigDir();
    const gpuInfoPath = path.join(configDir, 'gpu-info.json');

    try {
      fs.writeFileSync(gpuInfoPath, JSON.stringify(gpuInfo, null, 2));
      log('green', `  ✓ Saved GPU info to ${gpuInfoPath}`);
    } catch (err) {
      log('yellow', `  ⚠️  Could not save GPU info: ${err.message}`);
    }

  } catch (err) {
    log('yellow', `⚠️  Error detecting unified memory: ${err.message}`);
    log('cyan', '   Falling back to CPU-only mode');
    gpuInfo.recommendedModel = 'cpu-only';
  }

  return gpuInfo;
}

/**
 * Test-load a specific model to verify it actually works
 * @param {string} modelName - Model name (e.g., '1.1b-gpu', '0.6b-gpu')
 * @param {string} daemonBin - Path to daemon binary
 * @param {string} ortLibPath - Path to ONNX Runtime library
 * @returns {Promise<{success: boolean, model: string, reason?: string}>}
 */
async function testLoadModel(modelName, daemonBin, ortLibPath) {
  log('cyan', `  🔄 Test-loading ${modelName} model (max 30s)...`);

  // Create a minimal temporary config for testing
  const configDir = getConfigDir();
  const configPath = path.join(configDir, 'config.toml');
  const needsTempConfig = !fs.existsSync(configPath);

  if (needsTempConfig) {
    try {
      fs.mkdirSync(configDir, { recursive: true });
      fs.writeFileSync(configPath, generateDefaultConfig());
      log('green', '✓ Created default configuration');
    } catch (err) {
      log('yellow', `    ⚠️  Could not create config: ${err.message}`);
    }
  }

  const modelFlag = `--test-model=${modelName}`;
  const cmd = `"${daemonBin}" ${modelFlag} --dry-run 2>&1`;
  let env;
  if (process.platform === 'darwin') {
    // macOS: Only ORT_DYLIB_PATH needed (defensive, for forward compat)
    // DYLD_LIBRARY_PATH not needed — all ORT deps are system frameworks at absolute paths
    // LD_LIBRARY_PATH and CUDA_HOME are Linux-only concepts
    env = {
      ...process.env,
      ORT_DYLIB_PATH: ortLibPath,
      RUST_LOG: 'info'
    };
  } else {
    // Linux: CUDA paths + LD_LIBRARY_PATH for GPU acceleration
    const cudaPaths = detectCudaLibraryPaths();
    const nativeLibPath = path.join(__dirname, 'lib', 'native');
    const ldLibraryPath = [...cudaPaths, nativeLibPath].join(':');
    env = {
      ...process.env,
      ORT_DYLIB_PATH: ortLibPath,
      LD_LIBRARY_PATH: ldLibraryPath,
      CUDA_HOME: '/usr/local/cuda',
      RUST_LOG: 'info'
    };
  }

  try {
    const output = execSync(cmd, {
      encoding: 'utf8',
      timeout: 30000,
      env
    });
    // Exit code 0 — check for the definitive success marker
    if (output.includes('Dry-run complete')) {
      log('green', `    ✓ ${modelName} verified (dry-run passed)`);
      return { success: true, model: modelName };
    }
    // Exit 0 but no success marker — treat as inconclusive
    log('yellow', `    ⚠️ ${modelName} dry-run inconclusive`);
    return { success: false, model: modelName, reason: 'no success marker in output' };
  } catch (err) {
    // Non-zero exit — genuine failure, do NOT parse output for partial matches
    const output = (err.stdout || '') + (err.stderr || '');
    log('yellow', `    ⚠️ ${modelName} dry-run failed`);
    if (output.length > 0) {
      // Show first meaningful line for diagnostics
      const lines = output.split('\n').filter(l => l.includes('ERROR') || l.includes('error') || l.includes('not found'));
      if (lines.length > 0) {
        log('cyan', `      ${lines[0].trim().substring(0, 120)}`);
      }
    }
    return { success: false, model: modelName, reason: output.slice(0, 200) };
  }
}

/**
 * Test models in order from best to worst, returning the first that works
 * @param {object} gpuInfo - GPU information from detectGPUVRAM()
 * @param {string} daemonBin - Path to daemon binary
 * @param {string} ortLibPath - Path to ONNX Runtime library
 * @returns {Promise<{recommendedModel: string, tested: boolean, vramVerified?: boolean, fallbackToCpu?: boolean}>}
 */
async function testModelsInOrder(gpuInfo, daemonBin, ortLibPath) {
  log('cyan', '\n🧪 Testing models on your GPU...');
  if (process.platform === 'darwin') {
    log('cyan', `   GPU: ${gpuInfo.gpuName || 'Unknown'} with ${gpuInfo.totalMemoryGB}GB unified memory`);
  } else {
    log('cyan', `   GPU: ${gpuInfo.gpuName || 'Unknown'} with ${gpuInfo.vramGB}GB VRAM`);
  }

  if (!gpuInfo.hasGPU) {
    log('cyan', '  No GPU - skipping model tests');
    return { recommendedModel: 'cpu-only', tested: false };
  }

  if (!fs.existsSync(daemonBin)) {
    log('yellow', '  ⚠️  Daemon binary not found, skipping model tests');
    return { recommendedModel: gpuInfo.recommendedModel, tested: false };
  }

  // Test models in order from best to worst
  const modelsToTest = [];

  if (process.platform === 'darwin') {
    // macOS: test CoreML models (native Apple Neural Engine acceleration)
    modelsToTest.push('1.1b-coreml');
  } else {
    // Linux: test ONNX GPU models based on VRAM
    if (gpuInfo.vramMB >= 5500) {
      modelsToTest.push('1.1b-gpu');
    }
    if (gpuInfo.vramMB >= 3500) {
      modelsToTest.push('0.6b-gpu');
    }
  }

  if (modelsToTest.length === 0) {
    log('cyan', '  Insufficient VRAM for GPU models');
    return { recommendedModel: 'cpu-only', tested: false };
  }

  log('cyan', `  Testing ${modelsToTest.length} model(s)...\n`);

  for (const model of modelsToTest) {
    const result = await testLoadModel(model, daemonBin, ortLibPath);
    if (result.success) {
      log('green', `\n  ✓ Selected: ${model} (verified working)`);

      // Update config with tested model (if config exists and is on "auto")
      updateConfigWithTestedModel(model);

      return {
        recommendedModel: model,
        tested: true,
        vramVerified: true
      };
    }
  }

  // All tests failed - fall back to CPU
  log('yellow', '\n  ⚠️  All GPU models failed to load');
  log('cyan', '     Falling back to CPU-only mode');
  return {
    recommendedModel: 'cpu-only',
    tested: true,
    fallbackToCpu: true
  };
}

function detectSystemCapabilities() {
  const capabilities = {
    hasGPU: false,
    gpuName: null,
    gpuMemoryMB: 0,
    cpuCores: os.cpus().length,
    totalRAMGB: Math.round(os.totalmem() / (1024 * 1024 * 1024))
  };

  // Detect NVIDIA GPU and get details
  if (detectNvidiaGPU()) {
    capabilities.hasGPU = true;

    try {
      // Get GPU memory
      const gpuMemory = execSync('nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits', { encoding: 'utf8' });
      capabilities.gpuMemoryMB = parseInt(gpuMemory.trim());

      // Get GPU name
      const gpuName = execSync('nvidia-smi --query-gpu=name --format=csv,noheader', { encoding: 'utf8' });
      capabilities.gpuName = gpuName.trim();
    } catch (err) {
      // GPU detected but couldn't get details
      capabilities.gpuMemoryMB = 0;
    }
  }

  return capabilities;
}

function recommendOptimalModel(capabilities) {
  // Recommendation logic based on hardware
  if (capabilities.hasGPU) {
    if (capabilities.gpuMemoryMB >= 6000) {
      // High-end GPU: Recommend 1.1B model (best quality, full GPU acceleration)
      return {
        model: '1.1b',
        reason: `GPU detected: ${capabilities.gpuName} (${Math.floor(capabilities.gpuMemoryMB/1024)}GB VRAM)`,
        description: 'Best quality - Full GPU acceleration with FP32 precision',
        size: '~75MB download (FP32 + INT8 versions)',
        performance: '62x realtime speed on GPU'
      };
    } else if (capabilities.gpuMemoryMB >= 3500) {
      // Mid-range VRAM: Recommend 0.6B model
      return {
        model: '0.6b',
        reason: `GPU detected but limited VRAM (${Math.floor(capabilities.gpuMemoryMB/1024)}GB)`,
        description: 'Lighter model for lower VRAM systems',
        size: '~111MB',
        performance: 'Fast on GPU'
      };
    } else {
      // Very low VRAM: fall through to CPU recommendation
      return {
        model: '0.6b',
        reason: `GPU detected but very low VRAM (${Math.floor(capabilities.gpuMemoryMB/1024)}GB) - using CPU mode`,
        description: 'Lighter model for low VRAM systems',
        size: '~111MB',
        performance: 'CPU inference'
      };
    }
  } else {
    // CPU-only systems
    if (capabilities.cpuCores >= 8 && capabilities.totalRAMGB >= 16) {
      // Powerful CPU: Can handle 1.1B INT8
      return {
        model: '1.1b',
        reason: `Powerful CPU (${capabilities.cpuCores} cores, ${capabilities.totalRAMGB}GB RAM)`,
        description: 'INT8 quantized for fast CPU inference',
        size: '~1.1GB download',
        performance: 'Good CPU performance with INT8'
      };
    } else {
      // Weaker CPU: Recommend 0.6B
      return {
        model: '0.6b',
        reason: `CPU-only system (${capabilities.cpuCores} cores, ${capabilities.totalRAMGB}GB RAM)`,
        description: 'Lighter model for CPU-only systems',
        size: '~111MB',
        performance: 'Optimized for CPU'
      };
    }
  }
}

