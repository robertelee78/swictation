/**
 * Load expected checksums from checksums.txt
 * @returns {Map<string, string>} Map of filename -> sha512 hash
 */
function loadChecksums() {
  const checksumsPath = path.join(__dirname, 'checksums.txt');

  // Read directly in try/catch — avoids TOCTOU race with existsSync
  let content;
  try {
    content = fs.readFileSync(checksumsPath, 'utf8');
  } catch (err) {
    throw new Error('checksums.txt not found - package may be corrupted');
  }
  const checksums = new Map();

  for (const line of content.split('\n')) {
    // Skip comments and empty lines
    if (line.trim().startsWith('#') || line.trim() === '') {
      continue;
    }

    // Parse "hash  filename" format
    const match = line.match(/^([a-f0-9]{128})\s+(.+)$/);
    if (match) {
      const [, hash, filename] = match;
      checksums.set(filename, hash);
    }
  }

  return checksums;
}

/**
 * Calculate SHA-512 checksum of a file
 * @param {string} filePath - Path to file
 * @returns {Promise<string>} SHA-512 hash in hex format
 */
function calculateChecksum(filePath) {
  return new Promise((resolve, reject) => {
    const hash = crypto.createHash('sha512');
    const stream = fs.createReadStream(filePath);

    stream.on('data', (chunk) => {
      hash.update(chunk);
    });

    stream.on('end', () => {
      resolve(hash.digest('hex'));
    });

    stream.on('error', (err) => {
      reject(err);
    });
  });
}

/**
 * Verify downloaded file checksum matches expected value
 * @param {string} filePath - Path to downloaded file
 * @param {string} filename - Original filename for lookup
 * @param {Map<string, string>} checksums - Expected checksums map
 * @throws {Error} If checksum doesn't match or file is missing from checksums
 */
async function verifyChecksum(filePath, filename, checksums) {
  const expectedChecksum = checksums.get(filename);

  if (!expectedChecksum) {
    throw new Error(`No checksum found for ${filename} - package may be corrupted`);
  }

  log('cyan', '  Verifying file integrity...');
  const actualChecksum = await calculateChecksum(filePath);

  if (actualChecksum !== expectedChecksum) {
    throw new Error(
      `SECURITY: Checksum mismatch for ${filename}!\n` +
      `  Expected: ${expectedChecksum}\n` +
      `  Actual:   ${actualChecksum}\n` +
      `  This could indicate a corrupted download or supply chain attack.\n` +
      `  DO NOT extract this file. Please report this issue.`
    );
  }

  log('green', `  ✓ Checksum verified (SHA-512)`);
}

/**
 * Files the platform package ships deliberately and must keep, whatever the
 * downloaded GPU set happens to contain. `libonnxruntime.so` is the CPU /
 * fallback ONNX Runtime built into the platform package
 * (packages/linux-x64/scripts/build.sh step 8); generate-service.js points
 * LD_LIBRARY_PATH at it whenever gpu-libs has no ORT of its own. Deleting it
 * as "superseded" would strip the only runtime a CPU-only install has.
 */
const PLATFORM_OWNED_LIBS = new Set(['libonnxruntime.so']);

/**
 * The node_modules directory `startDir` sits under, or null in a dev checkout
 * / global-less layout. Resolved through realpath so a symlinked install
 * (npm link, pnpm store) cannot alias its way past the guard.
 */
function ownNodeModulesRoot(startDir = __dirname) {
  let dir;
  try {
    dir = fs.realpathSync(startDir);
  } catch {
    return null;
  }
  while (true) {
    if (path.basename(dir) === 'node_modules') return dir;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

/** True when `dir` is `root` or lives beneath it. Both must already be real paths. */
function isWithin(root, dir) {
  return dir === root || dir.startsWith(root + path.sep);
}

/**
 * Names in the downloaded GPU set that are allowed to displace a same-named
 * copy inside the platform package: shared objects (libfoo.so, libfoo.so.12,
 * libfoo.so.9.15.1) minus the files the platform package owns outright.
 */
function supersededLibNames(gpuLibNames) {
  const isSharedObject = (name) => /\.so(\.\d+)*$/.test(name);
  return new Set(gpuLibNames.filter((name) => isSharedObject(name) && !PLATFORM_OWNED_LIBS.has(name)));
}

/**
 * Remove GPU libraries that earlier installs extracted into the npm platform
 * package, now that the authoritative set lives in getGpuLibsDir() (ADR-035).
 * Only names the new directory also provides are removed, so platform-package
 * files that were never duplicated stay put. Cleanup is best-effort: a failure
 * here leaves a redundant library on disk, which must never fail the install.
 *
 * @param {string} gpuLibsDir - authoritative library directory, already populated
 */
function cleanupSupersededGpuLibs(gpuLibsDir) {
  try {
    const { resolveBinaryPaths, isPlatformPackageInstalled } = require('./src/resolve-binary');
    if (!isPlatformPackageInstalled()) return;

    const legacyDir = resolveBinaryPaths().libDir;
    if (!legacyDir || !fs.existsSync(legacyDir)) return;
    if (path.resolve(legacyDir) === path.resolve(gpuLibsDir)) return;

    // resolve-binary searches `npm root -g` before the local tree, so a local
    // install can resolve a GLOBAL platform package. Deleting from it would
    // let `npm install swictation` in any project mutate another install's
    // libraries. Only ever touch the node_modules tree we ourselves live in.
    const ownRoot = ownNodeModulesRoot();
    if (!ownRoot) return;
    let realLegacyDir;
    try {
      realLegacyDir = fs.realpathSync(legacyDir);
    } catch {
      return;
    }
    if (!isWithin(ownRoot, realLegacyDir)) {
      log('cyan', `  Skipping GPU library cleanup: ${legacyDir} is outside this install`);
      return;
    }

    const superseded = supersededLibNames(fs.readdirSync(gpuLibsDir));
    if (superseded.size === 0) return;

    const removed = [];
    for (const file of fs.readdirSync(legacyDir)) {
      if (!superseded.has(file)) continue;
      try {
        fs.unlinkSync(path.join(legacyDir, file));
        removed.push(file);
      } catch (err) {
        log('yellow', `    Could not remove superseded ${file}: ${err.message}`);
      }
    }

    if (removed.length > 0) {
      log('green', `  ✓ Removed ${removed.length} superseded GPU library file(s) from ${legacyDir}`);
      log('cyan', `    ${removed.join(', ')}`);
    }
  } catch (err) {
    log('yellow', `  ⚠️  GPU library cleanup skipped: ${err.message}`);
  }
}

/**
 * Download and extract the CUDA/ONNX-Runtime set for this GPU.
 *
 * @param {object} [facts] - resolved context facts (ADR-037 amendment 4).
 *   The caller has already probed the hardware once; re-probing here can
 *   disagree with that probe (driver reload mid-install, a second card) and
 *   then the receipt describes different hardware than the variant was chosen
 *   for. Absent facts fall back to probing so the function stays usable
 *   standalone.
 * @param {boolean} [facts.hasNvidiaGpu]
 * @param {object}  [facts.gpuCompute] - {smVersion, computeCap, gpuName}
 */
async function downloadGPULibraries(facts = {}) {
  const hasGPU = facts.hasNvidiaGpu !== undefined ? facts.hasNvidiaGpu : detectNvidiaGPU();

  if (!hasGPU) {
    log('cyan', '\nℹ No NVIDIA GPU detected - skipping GPU library download');
    log('cyan', '  CPU-only mode will be used');
    return;
  }

  log('green', '\n✓ NVIDIA GPU detected!');
  log('cyan', '📦 Detecting GPU architecture and downloading optimized libraries...\n');

  // GPU libraries live in the user data dir, OUTSIDE npm-owned trees
  // (ADR-035): extracting into the platform package meant every npm upgrade
  // deleted 1.5GB of libraries while the metadata receipt in the config dir
  // survived — the skip check then reported "already installed" and the
  // daemon silently fell back to CPU. detectCudaLibraryPaths() and
  // generate-service.js already prefer this location.
  const { getGpuLibsDir } = require('./src/paths');
  const gpuLibsDir = getGpuLibsDir();
  log('cyan', `   GPU libraries will be installed to: ${gpuLibsDir}\n`);

  // Compute capability: the caller's resolved fact when it has one, otherwise
  // a fresh probe. `null` from the context means "probed and could not tell",
  // which must fall through to the same guidance as a failed probe here.
  const gpuInfo = facts.gpuCompute !== undefined
    ? (facts.gpuCompute || { hasGPU: true, smVersion: null, computeCap: null, gpuName: null })
    : detectGPUComputeCapability();

  if (!gpuInfo.smVersion) {
    log('yellow', '⚠️  Could not detect GPU compute capability');
    log('cyan', '   Skipping GPU library download');
    log('cyan', '   You can manually download from:');
    log('cyan', '   https://github.com/robertelee78/swictation/releases/tag/gpu-libs-v1.2.0');
    return;
  }

  // Select appropriate package variant
  const packageInfo = selectGPUPackageVariant(gpuInfo.smVersion);

  if (!packageInfo.variant) {
    log('yellow', `⚠️  GPU architecture ${packageInfo.architectures} is not supported`);
    log('cyan', `   ${packageInfo.description}`);
    log('cyan', '   Supported architectures: sm_50 through sm_121');
    log('cyan', '   Your GPU may be too old or require a newer ONNX Runtime build');
    return;
  }

  log('cyan', `📦 Selected Package: ${packageInfo.variant.toUpperCase()}`);
  log('cyan', `   Architectures: ${packageInfo.architectures}`);
  log('cyan', `   Description: ${packageInfo.description}`);
  log('cyan', `   Examples: ${packageInfo.examples}\n`);

  const variant = packageInfo.variant;
  const releaseUrl = `https://github.com/robertelee78/swictation/releases/download/gpu-libs-v${GPU_LIBS_VERSION}/cuda-libs-${variant}.tar.gz`;
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'swictation-gpu-'));
  const tarPath = path.join(tmpDir, `cuda-libs-${variant}.tar.gz`);

  try {
    // Load checksums for verification
    let checksums;
    try {
      checksums = loadChecksums();
      log('green', '  ✓ Loaded integrity checksums');
    } catch (err) {
      log('red', `  ✗ Failed to load checksums: ${err.message}`);
      throw new Error('Cannot proceed without checksums - package integrity cannot be verified');
    }

    // Create directories
    if (!fs.existsSync(gpuLibsDir)) {
      fs.mkdirSync(gpuLibsDir, { recursive: true });
    }

    // Check if GPU libs are already installed by checking metadata file
    const configDir = getConfigDir();
    const gpuPackageInfoPath = path.join(configDir, 'gpu-package-info.json');

    let skipDownload = false;
    if (fs.existsSync(gpuPackageInfoPath)) {
      try {
        const existingMetadata = JSON.parse(fs.readFileSync(gpuPackageInfoPath, 'utf8'));
        // Skip only when the metadata matches AND the artifacts are verifiable
        // (ADR-035 + ADR-037 Phase B): the metadata is a receipt in the config
        // dir that survives upgrades; the goods must vouch for themselves.
        // "Verifiable" now means the per-file manifest describes every library
        // and every one of them still matches its recorded size. A directory
        // with no manifest is a pre-Phase-B install: nothing on disk can prove
        // those files are intact, so it is re-downloaded once rather than
        // blessed on the strength of a receipt and one sentinel — which is the
        // exact shape of the bug this skip check exists to prevent.
        const existing = require('./src/gpu-libs-manifest').readManifest(gpuLibsDir);
        const inventory = existing
          ? require('./src/gpu-libs-manifest').verifyInventory(existing, gpuLibsDir)
          : null;
        const receiptMatches = existingMetadata.version === GPU_LIBS_VERSION
          && existingMetadata.variant === variant;

        if (receiptMatches && existing && existing.variant === variant
          && existing.version === GPU_LIBS_VERSION && inventory.ok) {
          skipDownload = true;
          log('green', `  ✓ GPU libraries v${GPU_LIBS_VERSION} (${variant}) already installed`);
          log('cyan', `    Location: ${gpuLibsDir}`);
          log('cyan', `    Installed: ${existingMetadata.installedAt}`);
          log('cyan', `    Verified: ${inventory.checked} files match the recorded manifest`);
          log('cyan', `    Skipping download to save time and bandwidth`);
        } else if (receiptMatches && !existing) {
          log('yellow', '  ⚠️  GPU libraries present but not described by a per-file manifest');
          log('cyan', '     Re-downloading once so their integrity can be verified from now on');
        } else if (receiptMatches) {
          log('yellow', '  ⚠️  GPU library manifest does not match what is on disk — re-downloading');
          for (const item of [...inventory.missing, ...inventory.mismatched].slice(0, 5)) {
            log('cyan', `     ${item}`);
          }
        }
      } catch (err) {
        log('yellow', `    Warning: Could not read GPU package metadata: ${err.message}`);
      }
    }

    if (!skipDownload) {
      // Invalidate the receipt AND the manifest BEFORE downloading: if this
      // run is interrupted after a partial extraction, a surviving pair would
      // bless the incomplete set forever (ADR-035). Both are rewritten only
      // after full extraction succeeds.
      try {
        fs.unlinkSync(gpuPackageInfoPath);
      } catch {
        /* no receipt to invalidate */
      }
      try {
        fs.unlinkSync(require('./src/gpu-libs-manifest').manifestPath(gpuLibsDir));
      } catch {
        /* no manifest to invalidate */
      }
      // Download tarball with retry, resume, and progress
      log('cyan', `  Downloading ${variant} package...`);
      log('cyan', `  URL: ${releaseUrl}`);
      const dlResult = await downloadWithRetry(releaseUrl, tarPath);
      if (dlResult.skipped) {
        log('green', `  ✓ Package already downloaded and verified`);
      } else {
        log('green', `  ✓ Downloaded ${variant} package${dlResult.resumed ? ' (resumed)' : ''}`);
      }

      // Verify cryptographic checksum before extraction
      const filename = `cuda-libs-${variant}.tar.gz`;
      try {
        await verifyChecksum(tarPath, filename, checksums);
      } catch (err) {
        // Delete potentially malicious file
        fs.unlinkSync(tarPath);
        throw err;
      }

      // Extract tarball to gpu-libs directory
      log('cyan', '  Extracting libraries...');
      execSync(`tar -xzf "${tarPath}" -C "${tmpDir}"`, { stdio: 'inherit' });

      // Move libraries from extracted ${variant}/libs/ to gpu-libs directory,
      // hashing each file as it streams through (ADR-037 Phase B). The digest
      // is of the bytes that were actually written, in the same pass — not of
      // a later re-read, and not copied from the archive's own metadata. That
      // is what lets gpu-libs' check() finally say `healthy` instead of
      // `unknown`: forty files described by their own contents rather than one
      // sentinel standing in for the set.
      const gpuManifest = require('./src/gpu-libs-manifest');
      const extractedLibsDir = path.join(tmpDir, variant, 'libs');
      if (fs.existsSync(extractedLibsDir)) {
        const libFiles = fs.readdirSync(extractedLibsDir);
        const manifestFiles = [];
        for (const file of libFiles) {
          const srcPath = path.join(extractedLibsDir, file);
          if (!fs.statSync(srcPath).isFile()) continue;
          manifestFiles.push(
            await gpuManifest.copyAndHash(srcPath, path.join(gpuLibsDir, file), file)
          );
        }
        log('green', `  ✓ Extracted ${manifestFiles.length} libraries to ${gpuLibsDir}`);

        // Written BEFORE the receipt, and only from files that fully streamed:
        // an interruption between the two leaves a manifest with no receipt,
        // which reads as "not installed" rather than as a verified set.
        if (gpuManifest.writeManifest(gpuLibsDir, {
          variant,
          version: GPU_LIBS_VERSION,
          files: manifestFiles,
        })) {
          log('green', `  ✓ Recorded per-file integrity manifest (${manifestFiles.length} files)`);
        } else {
          log('yellow', '  ⚠️  Could not write the GPU library manifest');
          log('cyan', '     Integrity will report as unverified until the next install');
        }
      } else {
        throw new Error(`Expected directory not found: ${extractedLibsDir}`);
      }

      // Cleanup
      fs.unlinkSync(tarPath);
      execSync(`rm -rf "${path.join(tmpDir, variant)}"`, { stdio: 'ignore' });

      // Save GPU package info for systemd service generation
      const packageMetadata = {
        variant: packageInfo.variant,
        architectures: packageInfo.architectures,
        smVersion: gpuInfo.smVersion,
        computeCap: gpuInfo.computeCap,
        gpuName: gpuInfo.gpuName,
        version: GPU_LIBS_VERSION,
        libsPath: gpuLibsDir,
        installedAt: new Date().toISOString()
      };

      try {
        fs.writeFileSync(gpuPackageInfoPath, JSON.stringify(packageMetadata, null, 2));
        log('green', `   ✓ Saved package metadata to ${gpuPackageInfoPath}`);
      } catch (err) {
        log('yellow', `   ⚠️  Could not save package metadata: ${err.message}`);
      }
    }

    // Pre-ADR-035 installs put these same libraries inside the npm platform
    // package. With both copies on disk, LD_LIBRARY_PATH order decides which
    // CUDA/ORT build the daemon loads. Runs on the skip path too: the very
    // upgrade that reinstalls the platform package (restoring the shadowing
    // copies) is the one whose receipt still matches, so it downloads nothing.
    // The sentinel proves the authoritative set is really there first.
    if (fs.existsSync(path.join(gpuLibsDir, 'libonnxruntime.so'))) {
      cleanupSupersededGpuLibs(gpuLibsDir);
    }

    log('green', '\n✅ GPU acceleration enabled!');
    log('cyan', `   Architecture: ${packageInfo.architectures}`);
    log('cyan', `   Libraries: ${gpuLibsDir}`);
    log('cyan', '   Your system will use CUDA for faster transcription\n');

  } catch (err) {
    if (err instanceof InstallError) {
      console.log(err.format());
      log('cyan', '   Continuing with CPU-only mode');
      _installWarnings.push(`GPU library download failed (${err.code})`);
    } else {
      const wrapped = InstallError.fromSystemError(err, 'SW-E003', 'GPU library download failed', { url: releaseUrl });
      console.log(wrapped.format());
      log('cyan', '   Continuing with CPU-only mode');
      log('cyan', '\n   Manual installation:');
      log('cyan', `   1. Download: curl -L -C - -o /tmp/cuda-libs-${variant}.tar.gz ${releaseUrl}`);
      log('cyan', `   2. Extract: tar -xzf /tmp/cuda-libs-${variant}.tar.gz -C /tmp`);
      log('cyan', `   3. Install: cp /tmp/${variant}/libs/*.so ${gpuLibsDir}/`);
      _installWarnings.push('GPU library download failed');
    }
  } finally {
    try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch { /* ignore */ }
  }
}

/**
 * Download ONNX Runtime CoreML dylib for macOS
 * CoreML is Apple's GPU acceleration framework for neural networks
 */
async function downloadONNXRuntimeCoreML() {
  log('cyan', '\n📦 Setting up ONNX Runtime CoreML library for macOS...');

  // Version info - must match the CI build workflow (.github/workflows/build-macos.yml)
  // NOTE: Using 1.22.0 due to ORT 1.23.x regression with external data + CoreML
  // See: https://github.com/microsoft/onnxruntime/issues/26261
  // TODO: Upgrade to 1.23.x+ when fix (PR #26263) is released
  const ORT_VERSION = '1.22.0'; // ONNX Runtime version with CoreML support
  const releaseUrl = `https://github.com/robertelee78/swictation/releases/download/onnx-runtime-macos-v${ORT_VERSION}/libonnxruntime.dylib`;
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'swictation-macos-'));
  const dylibPath = path.join(tmpDir, 'libonnxruntime.dylib');

  // Target directory in npm package
  const nativeDir = path.join(__dirname, 'lib', 'native');
  const targetDylibPath = path.join(nativeDir, 'libonnxruntime.dylib');

  // Metadata file tracks dylib version + source to detect stale copies on upgrade
  // (follows the same pattern as gpu-package-info.json for GPU libraries)
  const metadataPath = path.join(nativeDir, 'ort-metadata.json');
  const currentVersion = require('./package.json').version;

  /**
   * Verify dylib code signature via codesign -dv (informational, non-fatal).
   * Returns { valid: boolean, teamId: string|null }.
   */
  function verifyDylibSignature(dylibToCheck) {
    try {
      // --verify: actually validate the signature (not just display)
      // --deep: verify nested code
      // --strict: enforce strict validation rules
      execFileSync('codesign', ['--verify', '--deep', '--strict', dylibToCheck], { stdio: 'pipe' });
      // If verification passes, get the Team ID for metadata
      let teamId = null;
      try {
        const sigInfo = execSync(`codesign -dv "${dylibToCheck}" 2>&1`, { encoding: 'utf8' });
        const teamMatch = sigInfo.match(/TeamIdentifier=(\S+)/);
        if (teamMatch && teamMatch[1] !== 'not set') {
          teamId = teamMatch[1];
        }
      } catch (e) { /* metadata extraction optional */ }
      return { valid: true, teamId };
    } catch (err) {
      // codesign exits non-zero if signature is invalid or missing
      return { valid: false, teamId: null };
    }
  }

  /**
   * Read ort-metadata.json. Returns parsed object or null.
   */
  function readOrtMetadata() {
    try {
      if (fs.existsSync(metadataPath)) {
        return JSON.parse(fs.readFileSync(metadataPath, 'utf8'));
      }
    } catch (err) {
      log('yellow', `    Warning: Could not read ORT metadata: ${err.message}`);
    }
    return null;
  }

  /**
   * Write ort-metadata.json with version, source, timestamp, and optional team_id.
   */
  function writeOrtMetadata(source, teamId) {
    const metadata = {
      version: currentVersion,
      source: source,
      copied_at: new Date().toISOString(),
    };
    if (teamId) {
      metadata.team_id = teamId;
    }
    fs.writeFileSync(metadataPath, JSON.stringify(metadata, null, 2), 'utf8');
    log('cyan', `    Wrote ORT metadata: v${currentVersion}, source=${source}`);
  }

  try {
    // --- Priority 1: Platform package (pre-signed with Developer ID from CI) ---
    // This is the preferred source: CI-signed dylib matching the daemon's signing identity
    const platformPkgLib = path.join(__dirname, 'node_modules', '@agidreams', 'darwin-arm64', 'lib', 'libonnxruntime.dylib');
    if (fs.existsSync(platformPkgLib)) {
      log('green', `  ✓ Found Developer ID signed ONNX Runtime from platform package`);
      log('cyan', `    Source: ${platformPkgLib}`);

      // Fast path: if metadata version matches current version, verify existing dylib
      const existingMetadata = readOrtMetadata();
      if (existingMetadata && existingMetadata.version === currentVersion && fs.existsSync(targetDylibPath)) {
        const sigResult = verifyDylibSignature(targetDylibPath);
        if (sigResult.valid) {
          log('green', `  ✓ ONNX Runtime dylib verified (v${currentVersion}, signature valid)`);
          log('cyan', `    Location: ${targetDylibPath}`);
          log('cyan', `    Installed: ${existingMetadata.copied_at}`);
          log('cyan', `    Skipping copy — same version reinstall`);
          return;
        }
        log('yellow', `    Signature check failed on existing dylib — will re-copy from platform package`);
      }

      // Create target directory if needed
      if (!fs.existsSync(nativeDir)) {
        fs.mkdirSync(nativeDir, { recursive: true });
      }

      // Copy the pre-signed library (unconditional overwrite on version mismatch or missing metadata)
      fs.copyFileSync(platformPkgLib, targetDylibPath);
      log('green', `  ✓ Copied signed library to ${targetDylibPath}`);

      // Verify signature and write metadata
      const sigResult = verifyDylibSignature(targetDylibPath);
      if (sigResult.valid) {
        log('green', `  ✓ Library has valid code signature${sigResult.teamId ? ` (Team: ${sigResult.teamId})` : ''}`);
      }
      writeOrtMetadata('platform-package', sigResult.teamId);

      return;
    }

    // --- Priority 2: Existing dylib with valid metadata (no platform package available) ---
    if (fs.existsSync(targetDylibPath)) {
      const existingMetadata = readOrtMetadata();
      if (existingMetadata && existingMetadata.version === currentVersion) {
        const sigResult = verifyDylibSignature(targetDylibPath);
        if (sigResult.valid) {
          log('green', `  ✓ ONNX Runtime dylib verified (v${currentVersion}, signature valid)`);
          log('cyan', `    Location: ${targetDylibPath}`);
          log('cyan', `    Source: ${existingMetadata.source}`);
          log('cyan', `    Installed: ${existingMetadata.copied_at}`);
          log('cyan', `    Skipping download — metadata matches`);
          return;
        }
        log('yellow', `    Existing dylib signature invalid — will re-download from GitHub`);
      } else if (existingMetadata) {
        log('cyan', `    Version mismatch: dylib is v${existingMetadata.version}, need v${currentVersion} — will re-download`);
      } else {
        log('cyan', `    No ORT metadata found — will re-download to ensure correct version`);
      }
    }

    // --- Priority 3: Download from GitHub release ---
    // Create directories
    if (!fs.existsSync(tmpDir)) {
      fs.mkdirSync(tmpDir, { recursive: true });
    }
    if (!fs.existsSync(nativeDir)) {
      fs.mkdirSync(nativeDir, { recursive: true });
    }

    // Download dylib with retry and progress
    log('cyan', `  Downloading CoreML-enabled ONNX Runtime...`);
    log('cyan', `  URL: ${releaseUrl}`);
    const dlResult = await downloadWithRetry(releaseUrl, dylibPath);
    if (dlResult.skipped) {
      log('green', `  ✓ CoreML dylib already downloaded and verified`);
    } else {
      log('green', `  ✓ Downloaded CoreML dylib${dlResult.resumed ? ' (resumed)' : ''}`);
    }

    // Verify it's a valid Mach-O library
    try {
      const fileOutput = execSync(`file "${dylibPath}"`, { encoding: 'utf8' });
      if (!fileOutput.includes('Mach-O') || !fileOutput.includes('arm64')) {
        throw new Error(`Invalid Mach-O library: ${fileOutput}`);
      }
      log('green', `  ✓ Verified Mach-O ARM64 library`);
    } catch (err) {
      log('red', `  ✗ Library verification failed: ${err.message}`);
      throw err;
    }

    // Copy to npm package native directory
    fs.copyFileSync(dylibPath, targetDylibPath);
    log('green', `  ✓ Installed to ${targetDylibPath}`);

    // Write metadata for GitHub-sourced dylib
    const sigResult = verifyDylibSignature(targetDylibPath);
    writeOrtMetadata('github-release', sigResult.valid ? sigResult.teamId : null);

    // Check for CoreML support
    try {
      const symbols = execSync(`nm -g "${targetDylibPath}" | grep -i coreml | head -5`, { encoding: 'utf8' });
      if (symbols) {
        log('green', `  ✓ CoreML symbols detected in library`);
      }
    } catch (err) {
      log('yellow', `  ⚠️  Could not verify CoreML symbols (may be normal)`);
    }

    // Cleanup temp file
    try {
      fs.unlinkSync(dylibPath);
    } catch (err) {
      // Cleanup is optional
    }

    log('green', `✅ CoreML-enabled ONNX Runtime ready for GPU acceleration`);

  } catch (err) {
    if (err instanceof InstallError) {
      console.log(err.format());
      _installWarnings.push(`CoreML ONNX Runtime download failed (${err.code})`);
    } else {
      const wrapped = new InstallError('SW-E010', 'Failed to download ONNX Runtime CoreML library', {
        cause: err.message,
        fix: `Manual installation:\n         1. Download: curl -L -C - -o "${targetDylibPath}" "${releaseUrl}"\n         2. Then re-run: npm install -g swictation`,
        original: err,
        context: { url: releaseUrl, dest: targetDylibPath },
      });
      console.log(wrapped.format());
      _installWarnings.push('CoreML ONNX Runtime download failed');
    }
    throw err;
  } finally {
    try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch { /* ignore */ }
  }
}

