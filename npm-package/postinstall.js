/**
 * Check if a specific model is already downloaded
 * @param {string} modelName - Model name (e.g., '0.6b-gpu', '1.1b-gpu', 'cpu-only')
 * @returns {boolean}
 */
function isModelDownloaded(modelName) {
  const modelDir = path.join(getDataDir(), 'models');

  // Map model names to directory names
  const modelDirs = {
    '0.6b': 'parakeet-tdt-0.6b-v3-onnx',
    '0.6b-gpu': 'parakeet-tdt-0.6b-v3-onnx',
    '1.1b': 'parakeet-tdt-1.1b-onnx',
    '1.1b-gpu': 'parakeet-tdt-1.1b-onnx',
    'cpu-only': 'parakeet-tdt-0.6b-v3-onnx',
    '0.6b-coreml': 'parakeet-tdt-0.6b-coreml',
    '1.1b-coreml': 'parakeet-tdt-1.1b-coreml'
  };

  const targetDir = modelDirs[modelName];
  if (!targetDir) return false;

  // Prefer the downloader's manifest-aware check (ADR-036: size-verified per
  // file) so a pre-existing corrupt/truncated tree triggers a re-download
  // instead of short-circuiting the verified path. Fall back to the legacy
  // existence checks below if the downloader or manifest is unavailable.
  const downloaderKeys = {
    '0.6b': '0.6b',
    '0.6b-gpu': '0.6b',
    'cpu-only': '0.6b',
    '1.1b': '1.1b',
    '1.1b-gpu': '1.1b',
    '0.6b-coreml': '0.6b-coreml',
    '1.1b-coreml': '1.1b-coreml'
  };
  try {
    const ModelDownloader = require('./lib/model-downloader.js');
    const downloader = new ModelDownloader({ modelDir });
    if (downloader.manifest()) {
      return downloader.isModelDownloaded(downloaderKeys[modelName]);
    }
  } catch {
    // fall through to legacy checks
  }

  const modelPath = path.join(modelDir, targetDir);
  if (!fs.existsSync(modelPath)) return false;

  // CoreML models use .mlmodelc directories — check for those instead of ONNX files
  if (modelName === '0.6b-coreml') {
    const coremlRequired = ['Encoder.mlmodelc', 'Decoder.mlmodelc', 'config.json'];
    return coremlRequired.every(entry => fs.existsSync(path.join(modelPath, entry)));
  }
  if (modelName === '1.1b-coreml') {
    const coremlRequired = ['encoder.mlmodelc', 'decoder.mlmodelc', 'joiner.mlmodelc', 'tokens.txt'];
    return coremlRequired.every(entry => fs.existsSync(path.join(modelPath, entry)));
  }

  // Verify required model files exist
  const requiredFiles = ['encoder.onnx', 'decoder.onnx', 'tokens.txt'];
  for (const file of requiredFiles) {
    const filePath = path.join(modelPath, file);
    // For INT8 models, check for .int8.onnx variants
    const int8FilePath = path.join(modelPath, file.replace('.onnx', '.int8.onnx'));

    if (!fs.existsSync(filePath) && !fs.existsSync(int8FilePath)) {
      return false;
    }
  }

  return true;
}

/**
 * Auto-download recommended model if not present
 * @param {string} recommendedModel - Model to download (e.g., '0.6b-gpu')
 */
async function autoDownloadModel(recommendedModel) {
  // Check if model already exists
  if (isModelDownloaded(recommendedModel)) {
    log('green', `✓ Recommended model (${recommendedModel}) already downloaded`);
    return true;
  }

  log('cyan', `\n📥 Auto-downloading recommended model: ${recommendedModel}`);
  log('cyan', '   This is a one-time download (may take a few minutes)...\n');

  try {
    const ModelDownloader = require(path.join(__dirname, 'lib', 'model-downloader.js'));

    // Map model names to downloader keys
    const modelMap = {
      '0.6b-gpu': '0.6b',
      '0.6b': '0.6b',
      '1.1b-gpu': '1.1b',
      '1.1b': '1.1b',
      'cpu-only': '0.6b',  // CPU-only uses same 0.6b model
      '0.6b-coreml': '0.6b-coreml',
      '1.1b-coreml': '1.1b-coreml'
    };

    const modelKey = modelMap[recommendedModel];
    if (!modelKey) {
      log('yellow', `⚠️  Unknown model type: ${recommendedModel}`);
      return false;
    }

    const downloader = new ModelDownloader({ force: false });

    // Download VAD + recommended model
    await downloader.downloadModels(['vad', modelKey]);

    log('green', '\n✓ Model downloaded successfully!');
    return true;
  } catch (err) {
    const wrapped = (err instanceof InstallError) ? err :
      InstallError.fromSystemError(err, 'SW-E008', 'Model download failed', { model: recommendedModel });
    console.log(wrapped.format());
    log('cyan', '   You can download manually later with:');
    log('green', `   swictation download-model ${recommendedModel}`);
    _installWarnings.push(`Model download failed for ${recommendedModel}`);
    return false;
  }
}

